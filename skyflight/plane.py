"""
飞机模型（重建版）
局部坐标：机头朝 -Z，右翼朝 +X，上为 +Y
只用验证过的 gfx.box 拼，几何一定正确
"""
from . import gfx

# 配色
BODY = (0.94, 0.94, 0.96)      # 机身白
ACCENT = (0.15, 0.35, 0.62)    # 蓝色涂装
ACCENT2 = (0.86, 0.22, 0.22)   # 红色条
DARK = (0.13, 0.13, 0.15)      # 起落架
GLASS = (0.40, 0.60, 0.78)     # 舱盖
GREY = (0.58, 0.60, 0.63)      # 机腹/金属
YELLOW = (0.95, 0.80, 0.25)

# ---- 主要尺寸（一架轻型飞机）
FUSE_L = 8.4          # 机身长（z 从 -1.6 到 6.8）
WING_SPAN = 11.0      # 翼展
WING_CHORD = 1.9      # 翼弦
TAIL_SPAN = 4.0       # 平尾展

# ---- 跑道尺寸（碰撞检测也要用，所以放在这里共享）
RUNWAY_LEN = 1400.0
RUNWAY_WID = 48.0
RUNWAY_TOP = 0.24     # 跑道面高度（沥青厚 0.24，铺在地面上）


def build_plane():
    v = []

    # ================= 机身（7 段，由机头到机尾）=================
    # (z中心, 长度, 宽, 高, y中心, 颜色)
    segs = [
        (-1.35, 0.60, 0.45, 0.45, 0.00, ACCENT),   # 桨毂罩
        (-0.75, 0.65, 0.60, 0.60, 0.00, BODY),     # 机头段
        (0.15, 1.25, 0.78, 0.82, 0.00, BODY),      # 前机身
        (1.55, 1.55, 0.82, 0.88, 0.00, BODY),      # 中机身
        (3.05, 1.50, 0.76, 0.82, 0.02, BODY),      # 后机身
        (4.45, 1.30, 0.60, 0.66, 0.08, ACCENT),    # 尾锥
        (5.45, 0.75, 0.42, 0.48, 0.14, ACCENT),    # 尾段
        (6.05, 0.45, 0.26, 0.30, 0.18, ACCENT),    # 尾尖
    ]
    for zc, ln, wd, ht, yc, col in segs:
        v += gfx.box(0.0, yc, zc, wd, ht, ln, col)

    # 蓝色+红色腰线
    v += gfx.box(0.0, 0.05, 1.55, 0.86, 0.16, 2.20, ACCENT)
    v += gfx.box(0.0, -0.18, 1.55, 0.86, 0.08, 2.20, ACCENT2)

    # ================= 主翼（左右各 3 段，做出锥形/后掠）=================
    # 用多段 box 拼出机翼：靠近机身宽、外侧窄、略后掠、带上反角
    wing_segs = [
        # (中心x, 段宽(x), 弦长(z), 弦中心z, y中心, 上反角抬高)
        (1.55, 2.60, 2.10, 2.30, -0.02),
        (3.55, 1.40, 1.90, 2.55, 0.10),
        (4.90, 1.30, 1.60, 2.80, 0.22),
    ]
    for side in (1, -1):
        for cx, span, chord, zc, yc in wing_segs:
            v += gfx.box(side * cx, yc, zc, span, 0.20, chord, BODY)
            # 后缘红色条纹
            v += gfx.box(side * cx, yc, zc + chord / 2 - 0.12, span, 0.21, 0.22, ACCENT2)
        # 翼尖小翼（竖直小片）
        v += gfx.box(side * 5.55, 0.34, 2.80, 0.10, 0.55, 1.35, ACCENT)

    # ================= 水平尾翼 =================
    for side in (1, -1):
        v += gfx.box(side * 1.05, 0.22, 5.05, 1.95, 0.16, 1.05, BODY)
        v += gfx.box(side * 1.05, 0.22, 5.50, 1.95, 0.17, 0.18, ACCENT2)

    # ================= 垂直尾翼（用几段 box 堆出梯形）=================
    vt = [
        (5.05, 0.70, 0.14, 0.90, 2.35, 0.60),
        (5.45, 0.60, 0.14, 1.15, 2.20, 0.70),
        (5.95, 0.50, 0.14, 1.55, 2.05, 0.75),
        (6.35, 0.40, 0.13, 1.85, 1.95, 0.60),
    ]
    for zc, ln, wd, ht, yc, _ in vt:
        yc = yc / 2.0 + 0.22
        v += gfx.box(0.0, yc, zc, wd, ht, ln, ACCENT)

    # ================= 座舱盖 =================
    v += gfx.box(0.0, 0.48, 0.30, 0.66, 0.26, 1.55, GLASS)
    v += gfx.box(0.0, 0.62, 0.30, 0.48, 0.10, 1.30, GLASS)
    v += gfx.box(0.0, 0.30, -0.50, 0.54, 0.20, 0.45, GLASS)

    # ================= 发动机罩 + 螺旋桨 =================
    v += gfx.box(0.0, 0.00, -1.70, 0.50, 0.50, 0.30, DARK)
    v += gfx.box(0.0, 0.00, -1.90, 0.22, 0.22, 0.16, GREY)
    # 三片桨叶
    v += gfx.box(0.0, 0.95, -1.90, 0.10, 1.90, 0.06, DARK)
    v += gfx.box(-0.82, -0.42, -1.90, 1.64, 0.10, 0.06, DARK)
    v += gfx.box(0.82, -0.42, -1.90, 1.64, 0.10, 0.06, DARK)

    # ================= 起落架（前三点式）=================
    # 前轮
    v += gfx.box(0.0, -0.62, -0.30, 0.10, 0.55, 0.10, DARK)
    v += gfx.box(0.0, -0.92, -0.30, 0.20, 0.24, 0.20, DARK)
    # 主轮
    for side in (1, -1):
        v += gfx.box(side * 1.10, -0.62, 1.85, 0.10, 0.60, 0.10, DARK)
        v += gfx.box(side * 1.10, -0.94, 1.85, 0.24, 0.26, 0.42, DARK)

    # ================= 翼下灯 =================
    for side in (1, -1):
        v += gfx.box(side * 5.40, 0.10, 2.60, 0.12, 0.14, 0.14, YELLOW)

    return gfx.Mesh(v)


def build_shadow():
    """飞机的地面阴影：一个略大于机身的扁平暗色多边形

    平铺在地面上（y 很小），随机身偏航一起转，让飞机看起来是"停在地上"
    而不是浮在空中。因为没有实时阴影贴图，用这个便宜又有效的办法。
    """
    col = (0.06, 0.07, 0.09)
    v = []
    # 机身 + 机翼 + 平尾 三个矩形拼出机身俯视轮廓
    v += gfx.box(0.0, 0.0, 2.4, 1.5, 0.012, 9.0, col)      # 机身
    v += gfx.box(0.0, 0.0, 2.6, 11.2, 0.012, 3.0, col)     # 主翼
    v += gfx.box(0.0, 0.0, 5.3, 4.2, 0.012, 1.4, col)      # 平尾
    return gfx.Mesh(v)


def build_runway():
    """跑道：沥青 + 中线虚线 + 边线 + 跑道灯"""
    v = []
    L = RUNWAY_LEN
    W = RUNWAY_WID
    # 沥青板：从地面铺到 RUNWAY_TOP
    v += gfx.box(0.0, RUNWAY_TOP * 0.5, 0.0, W, RUNWAY_TOP, L, (0.20, 0.20, 0.22))
    n = 24
    for i in range(n):
        z = -L / 2 + (i + 0.5) * (L / n)
        v += gfx.box(0.0, RUNWAY_TOP + 0.02, z, 1.7, 0.06, L / n * 0.48, (0.93, 0.93, 0.88))
    for side in (1, -1):
        v += gfx.box(side * (W / 2 - 1.3), RUNWAY_TOP + 0.02, 0.0, 1.0, 0.06, L,
                     (0.93, 0.93, 0.88))
    for i in range(0, 27):
        z = -L / 2 + i * (L / 26)
        for side in (1, -1):
            v += gfx.box(side * (W / 2 + 2.2), RUNWAY_TOP + 0.31, z, 0.75, 0.95, 0.75,
                         (0.98, 0.86, 0.30))
    # 跑道两端编号
    for side in (1, -1):
        for k in range(4):
            v += gfx.box(side * (7.0 - k * 4.6), RUNWAY_TOP + 0.04, -L / 2 + 30.0,
                         2.2, 0.06, 12.0, (0.93, 0.93, 0.88))
    return gfx.Mesh(v)


def surface_height(x, z, terrain_h):
    """实际可落脚的地面高度 = 地形和跑道里更高的那个。

    碰撞检测必须用它，否则飞机会沉进跑道里。
    terrain_h 是地形高度（由调用方传进来，避免循环依赖）。
    """
    if abs(x) <= RUNWAY_WID * 0.5 and abs(z) <= RUNWAY_LEN * 0.5:
        return max(float(terrain_h), RUNWAY_TOP)
    return float(terrain_h)


